export function getLanguageDirection(lang: Language): 'rtl' | 'ltr' {
  return lang === 'ar' || lang === 'ur' ? 'rtl' : 'ltr';
}

export function formatPrice(priceInSAR: number, currency: Currency, lang: Language): string {
  const info = CURRENCY_RATES[currency] || CURRENCY_RATES.SAR;
  const converted = Math.round(priceInSAR * info.rate);
  const isRTL = lang === 'ar' || lang === 'ur';
  const symbol = lang === 'ar' ? info.symbolAr : info.symbolEn;
  return isRTL ? `${converted.toLocaleString(lang === 'ar' ? 'ar-SA' : 'ur-PK')} ${symbol}` : `${symbol} ${converted.toLocaleString('en-US')}`;
}

