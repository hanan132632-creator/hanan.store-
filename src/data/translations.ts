import { Currency, Language } from '../types';

export const CURRENCY_RATES: Record<Currency, { rate: number; symbolAr: string; symbolEn: string }> = {
  SAR: { rate: 1, symbolAr: 'ر.س', symbolEn: 'SAR' },
  AED: { rate: 0.98, symbolAr: 'د.إ', symbolEn: 'AED' },
  KWD: { rate: 0.082, symbolAr: 'د.ك', symbolEn: 'KWD' },
  USD: { rate: 0.27, symbolAr: '$', symbolEn: 'USD' }
};

export function formatPrice(priceInSAR: number, currency: Currency, lang: Language): string {
  const info = CURRENCY_RATES[currency] || CURRENCY_RATES.SAR;
  const converted = Math.round(priceInSAR * info.rate);
  const symbol = lang === 'ar' ? info.symbolAr : info.symbolEn;
  return lang === 'ar' ? `${converted.toLocaleString('ar-SA')} ${symbol}` : `${symbol} ${converted.toLocaleString('en-US')}`;
}

